final _rng = Random();
int _last = -1;

/// Zufälliger Schieben-Spruch für [name] in der aktuellen Sprache
/// (nie zweimal hintereinander derselbe).
String pushPhrase(String name) {
  final list = _kPushPhrases[L10n.lang] ?? _kPushPhrases['de']!;
  var i = _rng.nextInt(list.length);
  if (i == _last && list.length > 1) i = (i + 1) % list.length;
  _last = i;
  return list[i].replaceAll('{0}', name);
}
